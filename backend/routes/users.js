const router = require("express").Router();
const crypto = require("crypto");
const bcrypt = require("bcrypt");
const db = require("../db");
const { authenticate, ready, allow } = require("../middleware/auth");
const { audit } = require("../lib/security");
const { allocateUserId } = require("../lib/user-id");
router.use(authenticate, ready);
router.post("/", allow("IT Support"), async (req, res) => {
  const { full_name, email, role_name } = req.body || {};
  if (Object.prototype.hasOwnProperty.call(req.body || {}, "user_id")) {
    return res.status(400).json({ message: "User ID is generated by the system. Do not submit user_id." });
  }
  if (typeof full_name !== "string" || !full_name.trim() || full_name.length > 150 ||
    typeof email !== "string" || email.length > 255 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) ||
    !["Employee", "IT Support", "IT Security Officer"].includes(role_name))
    return res.status(400).json({ message: "Valid full_name, email and permitted role_name required" });
  const c = await db.getConnection();
  try {
    await c.beginTransaction();
    const [roles] = await c.execute("SELECT id FROM roles WHERE role_name=?", [role_name]);
    if (!roles.length) throw new Error("Missing role");
    const temporaryPassword = crypto.randomBytes(24).toString("base64url");
    const passwordHash = await bcrypt.hash(temporaryPassword, 12);
    const user_id = await allocateUserId(c);
    const [result] = await c.execute(`INSERT INTO users (user_id,full_name,email,password_hash,role_id,
     account_status,must_change_password,profile_completed) VALUES (?,?,?,?,?,'pending',1,0)`,
      [user_id, full_name.trim(), email.trim().toLowerCase(), passwordHash, roles[0].id]);
    await audit(c, req.user.id, "ACCOUNT_PROVISIONED", result.insertId, { role: role_name });
    await c.commit();
    res.status(201).json({
      message: "Pending Administrator approval", id: result.insertId, user_id,
      temporary_password: temporaryPassword,
      delivery_note: "Shown once to authorised IT Support. Deliver privately after identity verification. No email was sent."
    });
  } catch (e) {
    await c.rollback();
    if (e.code === "ER_DUP_ENTRY") return res.status(409).json({ message: "An account with this email or identifier already exists" });
    if (e.code === "USER_ID_SEQUENCE_MISSING" || e.code === "ER_NO_SUCH_TABLE") {
      return res.status(503).json({ message: "Account setup is incomplete. Ask the Administrator to run the User ID migration." });
    }
    throw e;
  } finally { c.release(); }
});
router.get("/", allow("Administrator"), async (req, res) => {
  const [users] = await db.execute(`SELECT u.id,u.user_id,u.full_name,u.email,u.account_status,r.role_name
 FROM users u JOIN roles r ON r.id=u.role_id ORDER BY u.id LIMIT 500`);
  res.json({ users });
});
router.post("/:id/decision", allow("Administrator"), async (req, res) => {
  const { decision, reason } = req.body || {};
  if (!/^[1-9]\d*$/.test(req.params.id) || !["approve", "reject"].includes(decision) ||
    typeof reason !== "string" || !reason.trim() || reason.length > 500)
    return res.status(400).json({ message: "Valid id, approve/reject decision and reason required" });
  const c = await db.getConnection();
  try {
    await c.beginTransaction();
    const [rows] = await c.execute("SELECT id,account_status FROM users WHERE id=? FOR UPDATE", [req.params.id]);
    if (!rows.length || rows[0].account_status !== "pending") {
      await c.rollback(); return res.status(409).json({ message: "Account must exist and be pending" });
    }
    await c.execute("UPDATE users SET account_status=? WHERE id=?", [decision === "approve" ? "active" : "disabled", req.params.id]);
    await audit(c, req.user.id, decision === "approve" ? "ACCOUNT_APPROVED" : "ACCOUNT_REJECTED", rows[0].id, { reason: reason.trim() });
    await c.commit(); res.json({ message: decision === "approve" ? "Account approved" : "Account rejected and disabled" });
  } catch (e) { await c.rollback(); throw e; } finally { c.release(); }
});
router.post("/:id/status", allow("Administrator"), async (req, res) => {
  const id = Number(req.params.id);
  const { status, reason } = req.body || {};

  if (
    !/^[1-9]\d*$/.test(req.params.id) ||
    !Number.isSafeInteger(id) ||
    !["active", "suspended", "disabled"].includes(status) ||
    typeof reason !== "string" ||
    !reason.trim() ||
    reason.length > 500
  ) {
    return res.status(400).json({
      message: "Valid user ID, status and reason are required",
    });
  }

  if (id === req.user.id) {
    return res.status(403).json({
      message: "You cannot change your own account status",
    });
  }

  const c = await db.getConnection();

  try {
    await c.beginTransaction();

    const [rows] = await c.execute(
      `SELECT u.id, u.account_status, r.role_name
       FROM users u
       JOIN roles r ON r.id = u.role_id
       WHERE u.id = ?
       FOR UPDATE`,
      [id]
    );

    const target = rows[0];

    if (!target) {
      await c.rollback();
      return res.status(404).json({ message: "User not found" });
    }

    if (target.role_name === "Administrator") {
      await c.rollback();
      return res.status(403).json({
        message: "Administrator accounts cannot be changed here",
      });
    }

    if (target.account_status === "disabled" && status === "active") {
      const [events] = await c.execute(
        `SELECT action
     FROM audit_logs
     WHERE target_id = ?
       AND action IN (
         'ACCOUNT_PROVISIONED',
         'ACCOUNT_APPROVED',
         'ACCOUNT_REJECTED',
         'ACCOUNT_DISABLED',
         'ACCOUNT_SUSPENDED',
         'ACCOUNT_REACTIVATED'
       )
     ORDER BY id DESC
     LIMIT 1`,
        [id]
      );

      if (events[0]?.action !== "ACCOUNT_DISABLED") {
        await c.rollback();
        return res.status(409).json({
          message: "This account requires an approval review before reactivation",
        });
      }
    }
    const permitted = {
      active: ["suspended", "disabled"],
      locked: ["suspended", "disabled"],
      suspended: ["active", "disabled"],
      disabled: ["active"],
    };

    if (!permitted[target.account_status]?.includes(status)) {
      await c.rollback();
      return res.status(409).json({
        message: "This status change is not permitted",
      });
    }

    await c.execute(
      `UPDATE users
       SET account_status = ?,
           failed_login_attempts = 0,
           locked_until = NULL
       WHERE id = ?`,
      [status, id]
    );

    await c.execute(
      "DELETE FROM auth_sessions WHERE user_id = ?",
      [id]
    );

    const actions = {
      active: "ACCOUNT_REACTIVATED",
      suspended: "ACCOUNT_SUSPENDED",
      disabled: "ACCOUNT_DISABLED",
    };

    await audit(c, req.user.id, actions[status], id, {
      previous_status: target.account_status,
      new_status: status,
      reason: reason.trim(),
    });

    await c.commit();

    res.json({
      message: `Account ${status === "active" ? "reactivated" : status}. Previous sessions revoked.`,
    });
  } catch (error) {
    await c.rollback();
    throw error;
  } finally {
    c.release();
  }
});

module.exports = router;
